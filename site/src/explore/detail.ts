// Episode detail panel: key numbers, posts-over-time sparkline, engagement breakdown, per-agent trigger codes,
// classifier panel and the seed's lineage. Everything shown is a number, an enum or an opaque id.
import { h, s } from '../util/dom.js';
import { BAND_LABEL, dimLabel, modelInfo, seedFamily } from './data.js';
import type { Episode } from './types.js';
import type { Ctx } from './ui.js';
import { num, short } from './ui.js';

export function renderDetail(host: HTMLElement, ctx: Ctx, e: Episode, focus: boolean): void {
  const { ex } = ctx;
  const seed = ex.seeds[e.record_id];
  const mi = modelInfo(ex, e.model);
  const fam = seedFamily(ex, e.record_id);
  const close = (): void => ctx.closeEpisode();
  const kv = (k: string, v: string, title?: string): HTMLElement[] => [h('dt', { title: title ?? null }, k), h('dd', null, v)];
  const seedBtn = (id: string): HTMLElement => h('button.ex-link.mono', { type: 'button', 'aria-label': `Seed ${id}: list its episodes`,
    onclick: () => ctx.set({ seed: id, view: 'episodes', page: 0, ep: '' }, true) }, short(id));
  const siblings = ex.episodes.filter((x) => x.record_id === e.record_id && x.run_id !== e.run_id)
    .sort((a, b) => b.instigation_score - a.instigation_score);
  const eng = e.engagement;
  const engRows: [string, number][] = [['Board reads', eng.board_reads], ['Relay connections', eng.relay_connections],
    ['Board references', eng.board_refs], ['Agents engaged', eng.agents_engaged]];
  const engMax = Math.max(1, ...engRows.map(([, v]) => v));
  const h2 = h('h2', { tabindex: '-1', id: 'ex-detail-h' }, e.run_id);
  host.replaceChildren(
    h('div.ex-d-head', null, h2,
      h('button.ex-btn.ex-close', { type: 'button', 'aria-label': 'Close episode detail', onclick: close }, '×')),
    h('p.ex-d-tags', null,
      h('span.ex-pill', null, e.goal), h('span.ex-pill', null, dimLabel(ex, 'model', e.model), mi?.retired ? ' · retired' : ''),
      h('span.ex-pill', null, dimLabel(ex, 'channel', e.channel)), h('span.ex-pill.mono', null, e.trigger_code)),
    h('dl.ex-kv', null,
      kv('Writers', `${e.n_writers} of ${e.n_agents}`), kv('Instigation score', num(e.instigation_score)),
      kv('I', num(e.I), 'Instigation component'), kv('S mean', num(e.S_mean), 'Mean stickiness component'),
      kv('Write fraction', num(e.write_fraction)), kv('Time to first write', e.run_ttfw_s === null ? '–' : `${num(e.run_ttfw_s, 1)} s`),
      kv('First write step', num(e.run_first_write_step)), kv('Pile-in onset', e.pile_in_onset_t_s === null ? '–' : `${num(e.pile_in_onset_t_s, 1)} s`),
      kv('Step budget', num(e.budget)), kv('Episode no.', String(e.rep), 'Episode counter assigned by the search: unique per run, not a replicate index'), kv('Classifier errors', String(e.classifier_errors)),
      kv('Elite in', e.elite_in.length ? `${e.elite_in.length} cell${e.elite_in.length > 1 ? 's' : ''}` : 'no cell')),
    h('h3', null, 'Posts over time'),
    spark(e),
    h('h3', null, 'Engagement', h('span.muted', null, ` · score ${num(eng.engagement_score)}`)),
    h('dl.ex-bars', null, engRows.flatMap(([k, v]) => [h('dt', null, k),
      h('dd', null, h('span.ex-bar', { style: `width:${(v / engMax) * 100}%`, 'aria-hidden': 'true' }), h('span.ex-bar-v', null, num(v)))])),
    h('h3', null, 'Trigger codes per agent'),
    e.agent_codes.length
      ? h('ol.ex-codes', { start: '0' }, e.agent_codes.map((c, i) => h('li', null, h('span.muted', null, `agent ${i}`), ' ', c ? h('code', null, c) : h('span.muted', null, 'no code (did not write)'))))
      : h('p.muted', null, 'No per-agent codes.'),
    h('p.ex-small', null, e.panel
      ? [`Classifier panel: ${e.panel.slugs.map((sl) => dimLabel(ex, 'model', sl)).join(', ') || '–'}`,
        ` · mean agreement ${e.panel.agreement_mean === null ? '–' : num(e.panel.agreement_mean, 2)}`]
      : 'Single classifier (no panel).'),
    h('p.ex-small.muted', { hidden: !e.elite_in.length }, 'Elite cells: ', e.elite_in.map((k, i) => [i ? ', ' : '', h('code', null, k)])),
    h('h3', null, 'Seed'),
    h('dl.ex-kv', null,
      kv('Record', e.record_id), kv('Length', seed ? `${seed.seed_chars} chars (${BAND_LABEL[seed.length_band] ?? seed.length_band})` : '–'),
      kv('Origin', seed ? `${seed.origin}${seed.bootstrap ? ', bootstrap' : ''}` : '–'), kv('Generation', String(e.generation)),
      kv('Generated by', seed?.gen_model ? dimLabel(ex, 'model', seed.gen_model) : '–')),
    h('div.ex-lin', null,
      h('span.muted', null, 'Lineage: '),
      fam.ancestors.length ? fam.ancestors.flatMap((a) => [seedBtn(a), h('span.muted', { 'aria-hidden': 'true' }, ' → ')]) : h('span.muted', null, 'root → '),
      h('strong.mono', null, short(e.record_id)),
      fam.children.length ? [h('span.muted', { 'aria-hidden': 'true' }, ' → '), h('span.muted', null, `${fam.children.length} children: `),
        fam.children.slice(0, 12).flatMap((c, i) => [i ? ' ' : '', seedBtn(c)]), fam.children.length > 12 ? ' …' : ''] : null),
    h('p', null, h('button.ex-btn', { type: 'button', onclick: () => ctx.set({ seed: e.record_id, view: 'episodes', page: 0 }, true) },
      `All episodes of this seed (${siblings.length + 1})`)),
    h('ul.ex-sibs', { hidden: !siblings.length, 'aria-label': 'Other episodes of this seed' }, siblings.slice(0, 20).map((x) => h('li', null,
      h('button.ex-link', { type: 'button', onclick: () => ctx.openEpisode(x.run_id) }, x.run_id),
      h('span.muted', null, ` ${x.goal} · ${dimLabel(ex, 'model', x.model)} · ${x.n_writers}w · ${num(x.instigation_score)}`)))),
  );
  host.hidden = false;
  if (focus) h2.focus();
}

/** Two step lines on one count axis: cumulative posts and writers over episode time. */
function spark(e: Episode): Element {
  const pts = e.posts_over_time;
  if (!pts.length) return h('p.muted', null, 'No board writes in this episode.');
  const W = 320, H = 96, L = 28, R = 64, T = 8, B = 20;
  const tMax = Math.max(1, ...pts.map((p) => p[0]), e.pile_in_onset_t_s ?? 0, e.run_ttfw_s ?? 0);
  const yMax = Math.max(1, ...pts.map((p) => Math.max(p[1], p[2])));
  const X = (t: number): number => L + (t / tMax) * (W - L - R);
  const Y = (v: number): number => T + (1 - v / yMax) * (H - T - B);
  const path = (k: 1 | 2): string => {
    let d = `M${X(0)} ${Y(0)}`;
    let prev = 0;
    for (const p of pts) { d += `H${X(p[0])}V${Y(p[k])}`; prev = p[k]; }
    return `${d}H${X(tMax)}V${Y(prev)}`;
  };
  const last = pts[pts.length - 1] as [number, number, number];
  const labY = (v: number): number => Y(v) + 4;
  let yPosts = labY(last[1]), yWriters = labY(last[2]);
  if (Math.abs(yPosts - yWriters) < 12) { if (last[1] >= last[2]) yWriters = yPosts + 12; else yPosts = yWriters + 12; }
  const marks: Element[] = [];
  const rule = (t: number | null, label: string, row: number): void => {
    if (t === null) return;
    marks.push(s('line', { class: 'ex-sp-rule', x1: X(t), x2: X(t), y1: T, y2: H - B }));
    // right-aligned left of the rule, unless that would run into the y-axis labels (early events): then flip right
    const left = X(t) - 3 - label.length * 5.5 >= L;
    marks.push(s('text', { class: 'ex-axis', x: left ? X(t) - 3 : X(t) + 3, y: T + 8 + row * 12, 'text-anchor': left ? 'end' : 'start' }, label));
  };
  rule(e.run_ttfw_s, 'first write', 0);
  if (e.pile_in_onset_t_s !== null && e.pile_in_onset_t_s !== e.run_ttfw_s) rule(e.pile_in_onset_t_s, 'pile-in', 1);
  return h('figure.ex-spark', null,
    s('svg', { viewBox: `0 0 ${W} ${H}`, width: W, height: H, role: 'img',
      'aria-label': `Posts over time: ${last[1]} posts by ${last[2]} writers by ${Math.round(last[0])} s` },
    s('line', { class: 'ex-grid', x1: L, x2: W - R, y1: Y(0), y2: Y(0) }),
    s('text', { class: 'ex-axis', x: L - 4, y: Y(0) + 4, 'text-anchor': 'end' }, '0'),
    s('text', { class: 'ex-axis', x: L - 4, y: Y(yMax) + 4, 'text-anchor': 'end' }, String(yMax)),
    s('text', { class: 'ex-axis', x: L, y: H - 4 }, '0 s'),
    s('text', { class: 'ex-axis', x: W - R, y: H - 4, 'text-anchor': 'end' }, `${Math.round(tMax)} s`),
    marks,
    s('path', { class: 'ex-sp ex-sp1', d: path(1) }),
    s('path', { class: 'ex-sp ex-sp2', d: path(2) }),
    s('text', { class: 'ex-sp-l', x: W - R + 6, y: yPosts }, `posts ${last[1]}`),
    s('text', { class: 'ex-sp-l', x: W - R + 6, y: yWriters }, `writers ${last[2]}`)),
    h('figcaption.ex-legend', null, h('span', null, h('i.ex-sw.ex-sw1', { 'aria-hidden': 'true' }), 'posts (cumulative)'),
      h('span', null, h('i.ex-sw.ex-sw2', { 'aria-hidden': 'true' }), 'writers (cumulative)')));
}
