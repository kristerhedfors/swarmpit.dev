// Lineage view: the seed family tree. Columns are search generations, edges run parent -> child, and each
// node is coloured by the best instigation score among its (filtered) episodes.
import { h, s } from '../util/dom.js';
import { BAND_LABEL, dimLabel, filtersActive, lineage, rampBin } from './data.js';
import type { LineageNode } from './data.js';
import type { Ctx } from './ui.js';
import { legendRamp, num, short } from './ui.js';

const COL_W = 168, ROW_H = 22, PAD_X = 16, HEAD = 30;

export function renderLineage(host: HTMLElement, ctx: Ctx): void {
  const { ex, state } = ctx;
  const all = !filtersActive(state.filters, state.seed);
  const L = lineage(ex, ctx.eps, all);
  const max = L.nodes.reduce((m, n) => Math.max(m, n.best ?? 0), 0);
  const intro = h('p.ex-desc', null,
    'Every seed descends from a pilot or scratch seed; mutation seeds name their parent. Columns are generations, lines run from parent to ',
    'child. Filled dots are coloured by the best instigation score among the seed’s episodes that match the filters; hollow dots are ',
    'ancestors kept for context. Select a seed to list its episodes. Arrow keys move between seeds (left: parent, right: first child).');
  if (!L.nodes.length) { host.replaceChildren(intro, h('p.ex-none', null, 'No seeds match the filters.')); return; }
  const gx = new Map(L.gens.map((g, i) => [g, PAD_X + i * COL_W + 8]));
  const W = PAD_X * 2 + L.gens.length * COL_W, H = HEAD + L.rows * ROW_H + 8;
  const y = (n: LineageNode): number => HEAD + n.row * ROW_H + ROW_H / 2;
  const x = (n: LineageNode): number => gx.get(n.gen) ?? PAD_X;
  const byId = new Map(L.nodes.map((n) => [n.id, n]));
  const svg = s('svg', { class: 'ex-tree', width: W, height: H, viewBox: `0 0 ${W} ${H}`, role: 'group', 'aria-label': `Seed lineage: ${L.nodes.length} seeds over ${L.gens.length} generations` });
  for (const g of L.gens) {
    const gxv = gx.get(g) as number;
    svg.appendChild(s('line', { class: 'ex-tree-col', x1: gxv, x2: gxv, y1: HEAD - 6, y2: H - 4 }));
    svg.appendChild(s('text', { class: 'ex-tree-h', x: gxv - 6, y: 16 }, `gen ${g}`));
  }
  for (const n of L.nodes) {
    const p = n.parent ? byId.get(n.parent) : undefined;
    if (!p) continue;
    const x0 = x(p), y0 = y(p), x1 = x(n), y1 = y(n);
    const d = y1 - y0 > 4 ? `M${x0} ${y0}V${y1 - 4}Q${x0} ${y1} ${x0 + 4} ${y1}H${x1 - 7}` : `M${x0} ${y0}L${x1 - 7} ${y1}`;
    svg.appendChild(s('path', { class: 'ex-tree-e', d }));
  }
  const nodes: SVGGElement[] = [];
  for (const n of L.nodes) {
    const seed = ex.seeds[n.id];
    const bin = n.best === null ? null : rampBin(n.best, max);
    const label = `Seed ${n.id}, generation ${n.gen}, ${seed?.origin ?? 'unknown'} origin, `
      + (n.n ? `${n.n} matching episodes, best score ${num(n.best)}, up to ${n.maxWriters} writers` : 'ancestor only (no matching episodes)');
    const g = s('g', { class: `ex-node${n.context ? ' ex-ctx' : ''}${n.id === state.seed ? ' ex-on' : ''}`, tabindex: '-1', role: 'button',
      'data-fk': `t:${n.id}`, 'aria-label': `${label}. List its episodes.`, transform: `translate(${x(n)} ${y(n)})` },
    s('rect', { class: 'ex-node-hit', x: -10, y: -ROW_H / 2, width: COL_W - 6, height: ROW_H, rx: 4 }),
    s('circle', { r: 6, class: bin === null ? 'ex-dot-ctx' : `ex-dot q${bin}` }),
    s('text', { x: 12, y: 4, class: 'ex-node-t' }, short(n.id), s('tspan', { class: 'ex-node-s', dx: 6 }, n.best === null ? '' : n.best.toFixed(2)),
      n.maxWriters > 0 ? s('tspan', { class: 'ex-node-s', dx: 5 }, `${n.maxWriters}w`) : null));
    const pick = (): void => ctx.set({ seed: n.id, view: 'episodes', page: 0 }, true);
    g.addEventListener('click', pick);
    g.addEventListener('keydown', (e) => {
      const k = (e as KeyboardEvent).key;
      if (k === 'Enter' || k === ' ') { e.preventDefault(); pick(); return; }
      let to: LineageNode | undefined;
      if (k === 'ArrowDown') to = L.nodes[n.row + 1];
      else if (k === 'ArrowUp') to = L.nodes[n.row - 1];
      else if (k === 'ArrowLeft') to = n.parent ? byId.get(n.parent) : undefined;
      else if (k === 'ArrowRight') to = L.nodes.find((m) => m.parent === n.id);
      else if (k === 'Home') to = L.nodes[0];
      else if (k === 'End') to = L.nodes[L.nodes.length - 1];
      if (to) { e.preventDefault(); focusNode(nodes, to.row); }
    });
    ctx.tip.bind(g, () => [
      `Seed ${n.id}`,
      `Generation ${n.gen} · ${seed?.origin ?? '?'}${seed?.bootstrap ? ' · bootstrap' : ''}${seed?.gen_model ? ` · generated by ${dimLabel(ex, 'model', seed.gen_model)}` : ''}`,
      `Length ${seed ? `${seed.seed_chars} chars (${BAND_LABEL[seed.length_band] ?? seed.length_band})` : '?'}`,
      n.n ? `${n.n} matching episodes · best score ${num(n.best)} · max writers ${n.maxWriters}` : 'Ancestor only: no matching episodes',
      n.parent ? `Parent ${short(n.parent)}` : 'Root seed',
    ]);
    nodes.push(g);
    svg.appendChild(g);
  }
  (nodes.find((g) => g.classList.contains('ex-on')) ?? nodes[0])?.setAttribute('tabindex', '0');
  host.replaceChildren(intro, legendRamp('0', max.toFixed(2), 'Best score'),
    h('p.ex-note.muted', null, `${L.nodes.length} seeds${all ? '' : ' (matching seeds plus their ancestors)'}.`),
    h('div.ex-scroll.ex-tree-wrap', null, svg));
}

function focusNode(nodes: SVGGElement[], row: number): void {
  const t = nodes[row];
  if (!t) return;
  for (const g of nodes) g.setAttribute('tabindex', g === t ? '0' : '-1');
  t.focus();
  t.scrollIntoView({ block: 'nearest', inline: 'nearest' });
}
